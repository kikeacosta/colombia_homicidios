source("ocr2.R"); library(class)
nodot <- function(x) gsub(".", "", x, fixed = TRUE)
tag <- commandArgs(TRUE)[1]; fs <- list.files(".", sprintf("^cells_%s_.*rds$", tag))
R <- lapply(fs, readRDS)
cl <- rbindlist(lapply(seq_along(R), function(k) R[[k]]$cells[, f := k]))
cl[, lab := fifelse(!is.na(tess) & !is.na(sparse) & nodot(tess) == nodot(sparse) & nzchar(tess) & row <= 50, nodot(tess), NA_character_)]
cat("cells", nrow(cl), "| labelled (tess = sparse)", sum(!is.na(cl$lab)), "\n")
gl0 <- lapply(seq_len(nrow(cl)), function(i) cell_glyphs(R[[cl$f[i]]]$mats[[cl$cid[i]]]))
w1 <- unlist(lapply(which(!is.na(cl$lab) & nchar(cl$lab) == 1 & cl$lab != "1"), function(i) if (length(gl0[[i]]) == 1) ncol(gl0[[i]][[1]])))
dw <- median(w1); cat("digit width", dw, "\n")
gl <- lapply(seq_len(nrow(cl)), function(i) cell_glyphs(R[[cl$f[i]]]$mats[[cl$cid[i]]], dw))
cl[, ng := lengths(gl)]
ok <- which(!is.na(cl$lab) & nchar(cl$lab) == cl$ng)
cat("labelled cells whose glyph count = digits:", length(ok), "of", sum(!is.na(cl$lab)), "\n")
X <- do.call(rbind, lapply(ok, function(i) t(sapply(gl[[i]], glyph_feat))))
y <- unlist(lapply(ok, function(i) strsplit(cl$lab[i], "")[[1]]))
cat("glyphs", nrow(X), "\n"); print(table(y))
pr <- knn.cv(X, factor(y), k = 3)
cat("LOO accuracy", round(mean(pr == y), 4), "\n"); print(table(true = y, pred = pr))
saveRDS(list(cl = cl, gl = gl, X = X, y = y, dw = dw), sprintf("train_%s.rds", tag))
